import pdfplumber
import re

pdf_path1 = "2022.pdf"
pdf_path2 = "2023.pdf"
pdf_path3 = "2024.pdf"

def get_dic(pdf_path):
    results = []
    current_direction = None
    scores = []

    with pdfplumber.open(pdf_path) as pdf:
        for page in pdf.pages:
            text = page.extract_text()
            if not text:
                continue
            
            if "Направление подготовки" in text:
                if current_direction and scores:
                    avg_score = sum(scores) / len(scores)
                    results.append([current_direction, round(avg_score, 2)])
                    scores = []

                start = text.find("Направление подготовки:") + len("Направление подготовки:")
                end = text.find("\n", start)
                current_direction = text[start:end].strip().split()[0]

            tables = page.extract_tables()
            for table in tables:
                for row in table:
                    if not row:
                        continue
                    for cell in row:
                        if cell and re.fullmatch(r"\d{3}", str(cell).strip()):
                            val = int(cell)
                            if 150 <= val <= 350:
                                scores.append(val)

        if current_direction and scores:
            avg_score = sum(scores) / len(scores)
            results.append([current_direction, round(avg_score, 2)])

    direction_dict = {}

    for direction, score in results:
        if direction in direction_dict:
            direction_dict[direction].append(score)
        else:
            direction_dict[direction] = [score]

    final_result = {}
    for direction, scores in direction_dict.items():
        avg_score = sum(scores) / len(scores)
        final_result[direction] = round(avg_score, 2)
    
    return final_result

