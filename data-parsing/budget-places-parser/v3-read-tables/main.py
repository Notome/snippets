import matplotlib.pyplot as plt

# Получаем данные
dic2022 = get_dic(pdf_path1)
dic2023 = get_dic(pdf_path2)
dic2024 = get_dic(pdf_path3)

# Собираем только те направления, которые есть во всех трех годах
common_directions = set(dic2022.keys()) & set(dic2023.keys()) & set(dic2024.keys())
common_directions = sorted(common_directions)

# Подготавливаем данные для графика
years = [2022, 2023, 2024]
data = {}

for direction in common_directions:
    data[direction] = [
        dic2022[direction],
        dic2023[direction],
        dic2024[direction]
    ]

# Создаем график
plt.figure(figsize=(14, 8))

# Для каждой специальности рисуем линию
for direction in common_directions:
    scores = data[direction]
    # Полное название специальности из словаря
    full_name = education_codes.get(direction, direction)
    
    plt.plot(years, scores, marker='o', label=f"{direction} - {full_name}")

plt.title('Динамика средних баллов по специальностям (2022-2024)\n(только направления с данными за все три года)', fontsize=14)
plt.xlabel('Год', fontsize=12)
plt.ylabel('Средний балл', fontsize=12)
plt.grid(True, linestyle='--', alpha=0.7)

# Уменьшаем размер шрифта для легенды и выносим ее за пределы графика
plt.legend(bbox_to_anchor=(1.05, 1), loc='upper left', fontsize=8)
plt.tight_layout()

